import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),src=fs.readFileSync(path.join(root,'apps/prisma/web/gpu-scene.js'));
const m=await import('data:text/javascript;base64,'+src.toString('base64'));
const geometry=m.noteGeometry();
let out='// Generated by scripts/build-prisma-gpu-shaders.mjs; shared WebGL/GLES sources.\n#pragma once\nnamespace reverse_pc::prisma_gpu_sources {\n';
for(const [name,source]of Object.entries(m.SHADERS))out+=`inline constexpr char ${name}[]=R"PGPU(${source})PGPU";\n`;
out+='inline constexpr float vertices[]={'+Array.from(geometry.vertices,v=>Number(v).toPrecision(9)+'f').join(',')+'};\n';
out+='inline constexpr unsigned short indices[]={'+Array.from(geometry.indices).join(',')+'};\n}\n';
const target=path.resolve(process.argv[2]||path.join(root,'src/prisma_gpu_shaders.hpp'));
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('Native GPU shaders differ from WebGL; regenerate');}
else fs.writeFileSync(target,out);
