import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync(new URL('../apps/prisma/web/performance-policy.js',import.meta.url));
const {nextVisualQuality,visualBudget}=await import('data:text/javascript;base64,'+src.toString('base64'));
let checks=0;const check=(x,s)=>{assert.ok(x,s);checks++};
let state={quality:'high',slowFrames:0,fastFrames:0,cooldownUntil:0};
for(let i=0;i<19;i++)state=nextVisualQuality({...state,frameMs:28,now:1000+i*30});
check(state.quality==='high','avoid downgrade on single stutter');
state=nextVisualQuality({...state,frameMs:28,now:1570});
check(state.quality==='balanced','downgrade after sustained slow frames');
for(let i=0;i<120;i++)state=nextVisualQuality({...state,frameMs:10,now:1600+i*30});
check(state.quality==='balanced','cooldown must prevent oscillation');
for(let i=0;i<120;i++)state=nextVisualQuality({...state,frameMs:10,now:11000+i*30});
check(state.quality==='high','recover after sustained fast frames');
check(visualBudget('battery').material===0,'battery must retain simple materials');
check(visualBudget('high').particles>visualBudget('balanced').particles,'high visual budget not greater');
check(visualBudget('high',true).particles<visualBudget('battery').particles,'reduced motion budget wrong');
const engine=readFileSync(new URL('../apps/prisma/web/engine.js',import.meta.url),'utf8');
check(engine.includes('nextVisualQuality({...this.visualState'),'scene is not using quality policy');
check(engine.includes('visualBudget(qualityMode'),'particle cap not wired');
console.log(JSON.stringify({suite:'prisma-cycle6-quality',passed:checks}));
