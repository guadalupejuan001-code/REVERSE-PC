#!/usr/bin/env node
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {buildNormalAndroidRamdisk} from '../tools/android_normal_ramdisk.mjs';
import {parseNewcCpio} from '../tools/aosp_ramdisk_preflight.mjs';
const sha=b=>createHash('sha256').update(b).digest('hex');
const [input]=process.argv.slice(2);assert.ok(input,'usage: genuine combined initrd');
const original=readFileSync(input),before=sha(original);
const {initrd,report}=buildNormalAndroidRamdisk(original);
assert.equal(sha(original),before);
assert.equal(report.original_init_sha256,'d5c901a96c6e0bad8e3ee8110dc638c9336067fdafd4378860eaead51e4299ba');
assert.equal(report.output_initrd_sha256,sha(initrd));
assert.ok(initrd.length<12*1024*1024);
assert.equal(report.modules_required.length,19);
const first=parseNewcCpio(initrd.subarray(0,report.output_vendor_cpio_bytes));
for(const name of report.modules_required)assert.ok(first.some(x=>x.path==='lib/modules/'+name));
assert.ok(!first.some(x=>x.path.startsWith('res/')||x.path==='system/bin/recovery'));
const genericStart=report.output_vendor_cpio_bytes;
const generic=parseNewcCpio(initrd.subarray(genericStart,genericStart+report.source_generic_cpio_bytes));
const init=generic.find(x=>x.path==='init');
assert.ok(init&&(init.mode&0xf000)===0x8000);
assert.equal(sha(init.contents),report.original_init_sha256);
assert.equal(init.contents.readBigUInt64LE(24),0x2a4000n);
assert.equal(report.init_entry_file_offset,671744);
assert.equal(report.init_entry_bytes_hex.length,128);
assert.equal(report.init_entry_bytes_hex.slice(0,8),'9f2403d5');
const bad=Buffer.from(original);bad[100]^=1;
assert.throws(()=>buildNormalAndroidRamdisk(bad),/unexpected immutable source initrd/);
assert.equal(report.android_init_executed,false);
console.log(JSON.stringify({status:'normal_ramdisk_payloads_verified_not_booted',output_bytes:initrd.length,source_bytes:original.length,init_sha256:report.original_init_sha256,required_modules:report.modules_required.length,removed_recovery_members:report.omitted_recovery_members,input_unchanged:true}));
