/**
 * Interactive viewer for Frame Stream generated by authentic XI programs.
 * Java verifies XFS1 and displays ARGB pixels; world geometry, lane shapes,
 * colors and depth are never calculated by this Android host.
 */
public final class XiFrameStreamActivity extends Activity {
    private static final int[] WIDTHS={320,640,1280};
    private final ExecutorService executor=Executors.newSingleThreadExecutor();
    private final AtomicInteger serial=new AtomicInteger();
    private volatile boolean closed=false;
    private ImageView picture;
    private TextView status;
    private Bitmap current;
    private String source;
    private int quality=1,curve=128,phase=0;

    private int dp(int units){return Math.round(getResources().getDisplayMetrics().density*units);}
    private Button button(String label){
        Button b=new Button(this);
        b.setAllCaps(false);b.setText(label);b.setTextSize(13);
        b.setTextColor(Color.WHITE);
        b.setBackgroundTintList(android.content.res.ColorStateList.valueOf(0xff24425b));
        b.setMinHeight(0);b.setMinimumHeight(0);return b;
    }
    private static String asset(Activity activity)throws Exception{
        try(InputStream input=activity.getAssets().open("xi-render/super-frame-stream.xi")){
            ByteArrayOutputStream bytes=new ByteArrayOutputStream();
            byte[] part=new byte[4096];int n;
            while((n=input.read(part))!=-1){
                if(bytes.size()+n>64*1024)throw new IllegalArgumentException("XI source too large");
                bytes.write(part,0,n);
            }
            String value=new String(bytes.toByteArray(),StandardCharsets.UTF_8);
            if(!value.startsWith("#!reverse-pc-machine-v1\n"))
                throw new IllegalArgumentException("Unexpected XI program");
            return value;
        }
    }
    private static String program(String source,int width,int height,int start,
                                  int rows,int curve,int phase){
        int[] parameters={width,height,start,rows};
        StringBuilder text=new StringBuilder("#!reverse-pc-machine-v1\n");
        for(int group=0;group<4;group++)
            for(int byteIndex=0;byteIndex<4;byteIndex++){
                int value=(parameters[group]>>>(byteIndex*8))&255;
                text.append("store8 ").append(200+group*4+byteIndex)
                    .append(' ').append(value).append('\n');
            }
        text.append("store8 216 ").append(curve).append('\n');
        text.append("store8 217 ").append(phase).append('\n');
        return text.append(source.substring(source.indexOf('\n')+1)).toString();
    }
    @Override public void onCreate(Bundle saved){
        super.onCreate(saved);
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        WorkbenchActivity.immersive(this);
        FrameLayout root=new FrameLayout(this);root.setBackgroundColor(0xff101922);
        picture=new ImageView(this);
        picture.setScaleType(ImageView.ScaleType.FIT_CENTER);
        root.addView(picture,new FrameLayout.LayoutParams(-1,-1));
        status=new TextView(this);status.setTextColor(0xffecf6ff);
        status.setTextSize(13);status.setBackgroundColor(0xc0152638);
        status.setPadding(dp(12),dp(9),dp(12),dp(9));
        FrameLayout.LayoutParams top=new FrameLayout.LayoutParams(-2,-2,Gravity.TOP|Gravity.LEFT);
        top.setMargins(dp(12),dp(12),dp(95),0);root.addView(status,top);
        Button exit=button("Salir");exit.setOnClickListener(v->finish());
        FrameLayout.LayoutParams right=new FrameLayout.LayoutParams(dp(80),dp(43),Gravity.TOP|Gravity.RIGHT);
        right.setMargins(0,dp(8),dp(12),0);root.addView(exit,right);
        LinearLayout controls=new LinearLayout(this);
        controls.setGravity(Gravity.CENTER);controls.setOrientation(LinearLayout.HORIZONTAL);
        controls.setBackgroundColor(0xdb172b3c);controls.setPadding(dp(8),dp(5),dp(8),dp(6));
        Button left=button("Curva −");
        Button rightCurve=button("Curva +");
        Button advance=button("Avanzar");
        Button qualityButton=button("640×360");
        Button refresh=button("Actualizar");
        left.setOnClickListener(v->{curve=Math.max(0,curve-16);render();});
        rightCurve.setOnClickListener(v->{curve=Math.min(255,curve+16);render();});
        advance.setOnClickListener(v->{phase=(phase+18)&255;render();});
        qualityButton.setOnClickListener(v->{
            quality=(quality+1)%WIDTHS.length;
            int w=WIDTHS[quality];
            qualityButton.setText(w+"×"+w*9/16);render();
        });
        refresh.setOnClickListener(v->render());
        for(Button b:new Button[]{left,rightCurve,advance,qualityButton,refresh})
            controls.addView(b,new LinearLayout.LayoutParams(0,dp(48),1));
        root.addView(controls,new FrameLayout.LayoutParams(-1,-2,Gravity.BOTTOM));
        setContentView(root);
        try{source=asset(this);render();}
        catch(Exception error){status.setText("Frame Stream XI: "+error.getMessage());}
    }
    private void render(){
        if(closed||source==null)return;
        final int sequence=serial.incrementAndGet(),w=WIDTHS[quality],h=w*9/16,
                  c=curve,p=phase;
        status.setText("XI / Ether: generando "+w+"×"+h+"…");
        executor.execute(()->{
            Bitmap candidate=null;
            try{
                if(closed||serial.get()!=sequence)return;
                long startNanos=SystemClock.elapsedRealtimeNanos();
                // Private initial state, unrelated to desktop or BBY Q.
                byte[] pristine=NativeRuntime.initialize();
                List<XiFrameStreamCodec.Frame> windows=new ArrayList<>();
                int recordCount=0,transportBytes=0;
                for(int y=0;y<h;y+=120){
                    if(closed||serial.get()!=sequence||Thread.currentThread().isInterrupted())return;
                    String xi=program(source,w,h,y,Math.min(120,h-y),c,p);
                    ResultPacket result=ResultPacket.parse(NativeRuntime.execute(pristine,xi));
                    JSONObject message=new JSONObject(result.output.trim());
                    if(!"xi_frame_stream".equals(message.getString("type"))||
                       !"XFS1".equals(message.getString("format")))
                        throw new IllegalArgumentException("XI frame response is invalid");
                    byte[] bytes=java.util.Base64.getDecoder().decode(message.getString("payload"));
                    XiFrameStreamCodec.Frame decoded=XiFrameStreamCodec.decode(bytes);
                    if(decoded.width!=w||decoded.height!=h||decoded.revision!=1L||
                       decoded.recordCount!=message.getInt("records"))
                        throw new IllegalArgumentException("Mismatched XI viewport or revision");
                    windows.add(decoded);
                    recordCount+=decoded.recordCount;
                    transportBytes+=result.output.getBytes(StandardCharsets.UTF_8).length;
                }
                if(closed||serial.get()!=sequence)return;
                int[] pixels=XiFrameStreamCodec.materialize(windows,Runtime.getRuntime().maxMemory()/3);
                candidate=Bitmap.createBitmap(w,h,Bitmap.Config.ARGB_8888);
                candidate.setPixels(pixels,0,w,0,0,w,h);
                long ms=(SystemClock.elapsedRealtimeNanos()-startNanos)/1_000_000L;
                final int regions=recordCount,bytes=transportBytes;
                final Bitmap ready=candidate;candidate=null;
                runOnUiThread(()->{
                    if(closed||serial.get()!=sequence||isFinishing()){
                        ready.recycle();return;
                    }
                    Bitmap old=current;current=ready;
                    picture.setImageBitmap(ready);
                    if(old!=null&&!old.isRecycled())old.recycle();
                    status.setText(String.format(Locale.ROOT,
                        "XI XFS1 · %d×%d · %d regiones · %.1f KB · %d ms (no FPS)",
                        w,h,regions,bytes/1024.0,ms));
                });
            }catch(Throwable error){
                String message=error.getClass().getSimpleName()+": "+error.getMessage();
                runOnUiThread(()->{
                    if(!closed&&serial.get()==sequence&&!isFinishing())
                        status.setText("Frame Stream: "+message);
                });
            }finally{
                if(candidate!=null&&!candidate.isRecycled())candidate.recycle();
            }
        });
    }
    @Override protected void onResume(){
        super.onResume();WorkbenchActivity.immersive(this);
    }
    @Override protected void onDestroy(){
        closed=true;serial.incrementAndGet();executor.shutdownNow();
        if(picture!=null)picture.setImageDrawable(null);
        if(current!=null&&!current.isRecycled())current.recycle();
        super.onDestroy();
    }
}
