package com.reversepc.os;

/** Color-rich GPU material shading of XI-authored 4K geometry and texels. */
final class VelocityMaterialShader {
    static final String VERTEX=String.join("\n",
        "#version 300 es",
        "precision highp float;",
        "layout(location=0) in vec3 position;",
        "layout(location=1) in vec2 uv;",
        "layout(location=2) in float light;",
        "layout(location=3) in vec2 baseCount;",
        "layout(location=4) in vec2 tileStrength;",
        "uniform highp vec2 sourceSize;",
        "out highp vec2 texUV;",
        "out highp float shade;",
        "out highp vec3 viewPoint;",
        "flat out highp ivec2 material;",
        "flat out highp ivec2 textureParams;",
        "void main(){",
        "  highp float z=max(position.z,1.0);",
        "  highp vec2 ndc=vec2(2.0*position.x/sourceSize.x-1.0,1.0-2.0*position.y/sourceSize.y);",
        "  highp float depth=2.0*log2(1.0+z)/19.931570-1.0;",
        "  gl_Position=vec4(ndc*z,depth*z,z);",
        "  viewPoint=vec3((position.x-sourceSize.x*0.5)*z/(sourceSize.x*0.85),",
        "                 (sourceSize.y*0.5-position.y)*z/(sourceSize.x*0.85),z);",
        "  texUV=uv;",
        "  shade=light;",
        "  material=ivec2(baseCount+0.5);",
        "  textureParams=ivec2(tileStrength+0.5);",
        "}"
    )+"\n";
    static final String FRAGMENT=String.join("\n",
        "#version 300 es",
        "precision highp float;",
        "precision highp int;",
        "in highp vec2 texUV;",
        "in highp float shade;",
        "in highp vec3 viewPoint;",
        "flat in highp ivec2 material;",
        "flat in highp ivec2 textureParams;",
        "uniform highp sampler2D tileAtlas;",
        "uniform highp sampler2D palette;",
        "uniform highp vec2 renderSize;",
        "out vec4 color;",
        "float pattern(vec2 uv,int tile){",
        "  vec2 localUV=fract(uv/16.0)*15.0+0.5;",
        "  vec2 lookup=vec2(localUV.x/16.0,(float(tile*16)+localUV.y)/128.0);",
        "  return texture(tileAtlas,lookup).r*255.0;",
        "}",
        "void main(){",
        "  int base=material.x;",
        "  int count=max(material.y,1);",
        "  float intensity=clamp(shade*255.0,0.0,255.0);",
        "  float texel=8.0;",
        "  if(textureParams.y>0){",
        "    texel=pattern(texUV,textureParams.x);",
        "    intensity=clamp(intensity+(texel-8.0)*float(textureParams.y),0.0,255.0);",
        "  }",
        "  int index=base+int(floor(intensity*float(count-1)/255.0+0.5));",
        "  vec3 result=texelFetch(palette,ivec2(clamp(index,0,255),0),0).rgb;",
        "  if(base==0||base==1){",
        "    float skyH=clamp(gl_FragCoord.y/renderSize.y,0.0,1.0);",
        "    vec3 zenith=vec3(0.12,0.34,0.57);",
        "    vec3 horizon=vec3(0.64,0.77,0.86);",
        "    float farFactor=smoothstep(0.05,0.9,skyH);",
        "    result=mix(horizon,zenith,farFactor);",
        "  }else if(base==40){",
        "    float smallGrain=pattern(texUV*5.3,5)/15.0;",
        "    float largeGrain=texel/15.0;",
        "    result*=0.79+0.22*largeGrain+0.10*smallGrain;",
        "  }else if((base>=64&&base<184)||base==184||base==208||base==212||base==228){",
        "    vec3 V=normalize(-viewPoint);",
        "    vec3 N=normalize(cross(dFdx(viewPoint),dFdy(viewPoint)));",
        "    if(dot(N,V)<0.0)N=-N;",
        "    float cosTheta=clamp(dot(N,V),0.0,1.0);",
        "    float fresnel=pow(1.0-cosTheta,5.0);",
        "    vec3 reflected=reflect(-V,N);",
        "    float cloud=smoothstep(-0.35,0.7,reflected.y);",
        "    vec3 environment=mix(vec3(0.18,0.24,0.29),vec3(0.67,0.77,0.88),cloud);",
        "    vec3 sun=normalize(vec3(-0.43,0.82,0.39));",
        "    float specBase=max(dot(reflect(-sun,N),V),0.0);",
        "    if(base>=64&&base<184){",
        "      // Pearl clearcoat: broad sky reflection and a tight white highlight.",
        "      result=mix(result,environment,0.11+0.38*fresnel);",
        "      result+=vec3(1.0,0.98,0.94)*pow(specBase,76.0)*0.50;",
        "      result+=(texel-8.0)*0.0017;",
        "    }else if(base==184){",
        "      // Panoramic glass: dark interior tint and view-dependent reflectance.",
        "      result=mix(result*0.52,environment*0.92,0.27+0.60*fresnel);",
        "      result+=vec3(0.82,0.91,1.0)*pow(specBase,95.0)*0.33;",
        "    }else if(base==212){",
        "      // Wheel metal is brighter and smoother than tire/aero materials.",
        "      result=mix(result,environment,0.19+0.33*fresnel);",
        "      result+=vec3(0.95,0.97,1.0)*pow(specBase,52.0)*0.37;",
        "    }else if(base==228){",
        "      result=result*(0.75+0.09*cosTheta)+environment*(0.035+0.065*fresnel);",
        "    }else if(base==208){",
        "      result*=0.72+0.08*cosTheta;",
        "    }",
        "  }",
        "  color=vec4(clamp(result,0.0,1.0),1.0);",
        "}"
    )+"\n";
    private VelocityMaterialShader(){}
}
