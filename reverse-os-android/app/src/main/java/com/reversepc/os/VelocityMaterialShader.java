package com.reversepc.os;

/** Color-rich GPU material shading of XI-authored 4K geometry and texels. */
final class VelocityMaterialShader {
    static final String VERTEX=String.join("\n",
        "#version 300 es",
        "precision highp float;",
        "layout(location=0) in vec3 position;",
        "layout(location=1) in vec2 uv;",
        "layout(location=2) in float light;",
        "layout(location=3) in vec2 baseCount;",
        "layout(location=4) in vec2 tileStrength;",
        "uniform highp vec2 sourceSize;",
        "out highp vec2 texUV;",
        "out highp float shade;",
        "out highp vec3 viewPoint;",
        "flat out highp ivec2 material;",
        "flat out highp ivec2 textureParams;",
        "void main(){",
        "  highp float z=max(position.z,1.0);",
        "  highp vec2 ndc=vec2(2.0*position.x/sourceSize.x-1.0,1.0-2.0*position.y/sourceSize.y);",
        "  highp float depth=2.0*log2(1.0+z)/19.931570-1.0;",
        "  gl_Position=vec4(ndc*z,depth*z,z);",
        "  viewPoint=vec3((position.x-sourceSize.x*0.5)*z/(sourceSize.x*0.85),",
        "                 (sourceSize.y*0.5-position.y)*z/(sourceSize.x*0.85),z);",
        "  texUV=uv;",
        "  shade=light;",
        "  material=ivec2(baseCount+0.5);",
        "  textureParams=ivec2(tileStrength+0.5);",
        "}"
    )+"\n";
    static final String FRAGMENT=String.join("\n",
        "#version 300 es",
        "precision highp float;",
        "precision highp int;",
        "in highp vec2 texUV;",
        "in highp float shade;",
        "in highp vec3 viewPoint;",
        "flat in highp ivec2 material;",
        "flat in highp ivec2 textureParams;",
        "uniform highp sampler2D tileAtlas;",
        "uniform highp sampler2D palette;",
        "uniform highp vec2 renderSize;",
        "out vec4 color;",
        "",
        "// A procedural detail is evaluated in XI UV space: it stays on the model.",
        "float saturate(float x){return clamp(x,0.0,1.0);}",
        "float noise2(vec2 p){",
        "  vec2 i=floor(p),f=fract(p);",
        "  f=f*f*(3.0-2.0*f);",
        "  float a=fract(52.982919*fract(dot(i,vec2(0.0671106,0.00583715))));",
        "  float b=fract(52.982919*fract(dot(i+vec2(1,0),vec2(0.0671106,0.00583715))));",
        "  float c=fract(52.982919*fract(dot(i+vec2(0,1),vec2(0.0671106,0.00583715))));",
        "  float d=fract(52.982919*fract(dot(i+vec2(1,1),vec2(0.0671106,0.00583715))));",
        "  return mix(mix(a,b,f.x),mix(c,d,f.x),f.y);",
        "}",
        "float pattern(vec2 uv,int tile){",
        "  vec2 p=fract(uv/16.0)*15.0+0.5;",
        "  return texture(tileAtlas,vec2(p.x/16.0,(float(tile*16)+p.y)/128.0)).r*255.0;",
        "}",
        "vec3 atmosphere(vec3 d){",
        "  float up=saturate(d.y*0.5+0.5);",
        "  vec3 sky=mix(vec3(0.67,0.78,0.86),vec3(0.10,0.30,0.54),smoothstep(0.12,0.93,up));",
        "  float haze=exp(-abs(d.y)*5.5);",
        "  sky=mix(sky,vec3(0.88,0.87,0.79),0.20*haze);",
        "  // Cloud reflections are analytic, not a screen-space decoration.",
        "  float cloud=noise2(d.xz*3.2+vec2(d.y*1.8,0.0));",
        "  cloud=pow(smoothstep(0.48,0.79,cloud),1.3);",
        "  sky=mix(sky,vec3(0.92,0.96,1.0),cloud*0.22*up);",
        "  return sky;",
        "}",
        "vec3 reflectionEnvironment(vec3 dir){",
        "  vec3 upper=atmosphere(dir);",
        "  vec3 ground=vec3(0.16,0.19,0.21);",
        "  return mix(ground,upper,smoothstep(-0.09,0.07,dir.y));",
        "}",
        "vec3 filmic(vec3 c){",
        "  // Bounded contrast rolloff, keeping pearl highlights inside RGBA8.",
        "  c=max(c,vec3(0.0));",
        "  return clamp((c*(1.06*c+0.04))/(c*(1.05*c+0.13)+0.03),0.0,1.0);",
        "}",
        "void main(){",
        "  int base=material.x;",
        "  int count=max(material.y,1);",
        "  float intensity=saturate(shade)*255.0;",
        "  float texel=8.0;",
        "  if(textureParams.y>0){",
        "    texel=pattern(texUV,textureParams.x);",
        "    intensity=clamp(intensity+(texel-8.0)*float(textureParams.y),0.0,255.0);",
        "  }",
        "  int index=base+int(floor(intensity*float(count-1)/255.0+0.5));",
        "  vec3 albedo=texelFetch(palette,ivec2(clamp(index,0,255),0),0).rgb;",
        "",
        "  if(base==0||base==1){",
        "    vec2 screen=gl_FragCoord.xy/renderSize;",
        "    vec3 direction=normalize(vec3(screen.x*1.9-0.95,screen.y-0.55,1.0));",
        "    float v=saturate(screen.y);",
        "    vec3 sky=mix(vec3(0.72,0.81,0.88),vec3(0.11,0.34,0.57),smoothstep(0.07,0.93,v));",
        "    float m=noise2(direction.xz*3.0+vec2(v*1.8,0.0));",
        "    float clouds=smoothstep(0.61,0.79,m);",
        "    sky=mix(sky,vec3(0.93,0.95,0.96),0.16*clouds);",
        "    color=vec4(sky,1.0);return;",
        "  }",
        "  if(base==40){",
        "    // XI asphalt tile and a second procedural aggregate frequency.",
        "    float small=noise2(texUV*2.1);",
        "    float micro=noise2(texUV*7.0);",
        "    float rough=0.70+0.25*small+0.15*(micro-0.5);",
        "    vec3 road=albedo*rough;",
        "    float grit=smoothstep(0.64,0.88,micro);",
        "    road+=vec3(0.048,0.049,0.047)*grit;",
        "    float fog=saturate((viewPoint.z-3600.0)/24000.0);",
        "    road=mix(road,vec3(0.47,0.53,0.56),fog*0.28);",
        "    color=vec4(filmic(road),1.0);return;",
        "  }",
        "  if(base==224||base==225){",
        "    // True emissive lens response on the authored XI light geometry.",
        "    float path=smoothstep(0.1,0.45,saturate(shade));",
        "    vec3 emitter=base==224?vec3(1.0,0.065,0.12):vec3(0.87,0.95,1.0);",
        "    vec3 light=mix(albedo,emitter,0.55+0.40*path);",
        "    color=vec4(clamp(light,0.0,1.0),1.0);return;",
        "  }",
        "  bool paint=(base>=64&&base<184);",
        "  bool glass=(base==184);",
        "  bool metal=(base==212||base==241);",
        "  bool carbon=(base==228||base==226);",
        "  bool rubber=(base==208);",
        "  if(paint||glass||metal||carbon||rubber||base==240){",
        "    vec3 V=normalize(-viewPoint);",
        "    vec3 N=normalize(cross(dFdx(viewPoint),dFdy(viewPoint)));",
        "    if(dot(N,V)<0.0)N=-N;",
        "    float bump=saturate(length(fwidth(texUV))*0.12);",
        "    float micro=(texel-8.0)/8.0;",
        "    // Perturb only material response, not the real XI geometry/z buffer.",
        "    if(paint||metal||carbon||rubber){",
        "      vec3 U=normalize(abs(N.y)<0.9?cross(N,vec3(0.0,1.0,0.0)):",
        "        cross(N,vec3(1.0,0.0,0.0)));",
        "      vec3 W=normalize(cross(N,U));",
        "      float relief=(rubber?0.19:carbon?0.09:metal?0.06:0.021)*(1.0-bump);",
        "      N=normalize(N+U*micro*relief+W*(noise2(texUV*1.7)-0.5)*relief);",
        "    }",
        "    float facing=saturate(dot(N,V));",
        "    float F=pow(1.0-facing,5.0);",
        "    vec3 reflected=reflectionEnvironment(reflect(-V,N));",
        "    vec3 L=normalize(vec3(-0.43,0.82,0.39));",
        "    vec3 H=normalize(L+V);",
        "    float lambert=saturate(dot(N,L));",
        "    float nDotH=saturate(dot(N,H));",
        "    float film=smoothstep(-0.12,0.48,reflected.b-reflected.r);",
        "    if(paint){",
        "      // Pearl-white clearcoat: broad reflection plus sharp second lobe.",
        "      float spec=pow(nDotH,40.0)*0.22+pow(nDotH,115.0)*0.18;",
        "      vec3 diffuse=albedo*(0.80+0.27*lambert);",
        "      vec3 pearl=vec3(0.83,0.9,1.0)*max(0.0,micro)*0.045;",
        "      vec3 coat=reflected*(0.085+0.37*F);",
        "      vec3 result=diffuse+coat+pearl+vec3(1.0,0.97,0.91)*spec;",
        "      result+=reflected*film*0.055;",
        "      color=vec4(filmic(result),1.0);return;",
        "    }",
        "    if(glass){",
        "      // Dark interior glass: view-dependent sky reflection and glint.",
        "      float glassF=saturate(0.09+0.78*F);",
        "      vec3 tint=albedo*vec3(0.47,0.52,0.58);",
        "      vec3 result=mix(tint,reflected,glassF);",
        "      result+=vec3(0.74,0.83,0.94)*pow(nDotH,130.0)*0.32;",
        "      color=vec4(filmic(result),1.0);return;",
        "    }",
        "    if(metal){",
        "      float machined=(1.0-smoothstep(0.02,0.18,abs(fract(texUV.y*0.45)-0.5)))*0.05;",
        "      vec3 result=albedo*(0.60+0.22*lambert+machined);",
        "      result+=reflected*(0.18+0.46*F);",
        "      result+=vec3(0.90,0.94,1.0)*pow(nDotH,75.0)*0.32;",
        "      color=vec4(filmic(result),1.0);return;",
        "    }",
        "    if(carbon){",
        "      float weave=smoothstep(0.25,0.73,texel/15.0);",
        "      vec3 result=albedo*(0.68+0.15*lambert+0.06*weave);",
        "      result+=reflected*(0.035+0.13*F);",
        "      result+=vec3(0.64,0.72,0.79)*pow(nDotH,24.0)*0.08;",
        "      color=vec4(filmic(result),1.0);return;",
        "    }",
        "    if(rubber){",
        "      float grooves=1.0-smoothstep(0.10,0.24,abs(fract(texUV.y*0.6)-0.5));",
        "      float grit=noise2(texUV*4.0);",
        "      vec3 result=albedo*(0.66+0.18*lambert+0.11*grit-0.14*grooves);",
        "      color=vec4(filmic(result),1.0);return;",
        "    }",
        "    color=vec4(albedo*(0.76+0.18*lambert),1.0);return;",
        "  }",
        "  // Stable XI world colors; no additional objects or track edits.",
        "  color=vec4(filmic(albedo),1.0);",
        "}"
    )+"\n";
    private VelocityMaterialShader(){}
}
